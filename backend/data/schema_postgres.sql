-- Schema PostgreSQL do Odradek (Supabase, Neon ou qualquer Postgres). Idempotente: so cria o que falta.
-- Aplicado por repository.initialize() quando faltam tabelas e por db_copy ao preparar um banco vazio.
-- Regras para editar: uma instrucao termina em ponto e virgula no fim da linha, e os comentarios ocupam a linha toda.
-- Timestamps sao texto ISO-8601 (as consultas comparam strings), booleanos sao INTEGER 0 ou 1.

CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source TEXT NOT NULL,
  source_id TEXT,
  title TEXT NOT NULL,
  company TEXT NOT NULL DEFAULT '',
  location TEXT NOT NULL DEFAULT '',
  description TEXT NOT NULL DEFAULT '',
  url TEXT NOT NULL,
  posted_at TEXT,
  first_seen_at TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'new',
  applied_at TEXT,
  notes TEXT NOT NULL DEFAULT '',
  fingerprint TEXT NOT NULL UNIQUE,
  language TEXT NOT NULL DEFAULT 'unknown',
  language_confidence DOUBLE PRECISION NOT NULL DEFAULT 0,
  search_filter_id TEXT NOT NULL DEFAULT '',
  search_remote TEXT NOT NULL DEFAULT '',
  reviewed_at TEXT NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS jobs_status_idx ON jobs(status);
CREATE INDEX IF NOT EXISTS jobs_seen_idx ON jobs(first_seen_at DESC);
CREATE INDEX IF NOT EXISTS jobs_status_seen_idx ON jobs(status, first_seen_at DESC);

CREATE TABLE IF NOT EXISTS runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  started_at TEXT NOT NULL,
  finished_at TEXT,
  state TEXT NOT NULL,
  found_count INTEGER NOT NULL DEFAULT 0,
  message TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS ai_decisions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id BIGINT NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  decided_at TEXT NOT NULL,
  match_score INTEGER NOT NULL,
  should_apply INTEGER NOT NULL,
  letter_required INTEGER NOT NULL,
  reason TEXT NOT NULL,
  assessment_json TEXT NOT NULL DEFAULT '',
  scoring_version TEXT NOT NULL DEFAULT '',
  provider TEXT NOT NULL DEFAULT '',
  model TEXT NOT NULL DEFAULT '',
  resume_language TEXT NOT NULL DEFAULT '',
  apply_channel TEXT NOT NULL DEFAULT '',
  apply_result TEXT NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS ai_decisions_job_latest_idx ON ai_decisions(job_id, id DESC);

CREATE TABLE IF NOT EXISTS cover_letters (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id BIGINT NOT NULL UNIQUE REFERENCES jobs(id) ON DELETE CASCADE,
  language TEXT NOT NULL,
  provider TEXT NOT NULL,
  model TEXT NOT NULL,
  body TEXT NOT NULL,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS resumes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  language TEXT NOT NULL UNIQUE,
  original_filename TEXT NOT NULL DEFAULT '',
  stored_path TEXT NOT NULL,
  file_sha256 TEXT NOT NULL,
  extracted_text TEXT NOT NULL DEFAULT '',
  analysis_json TEXT NOT NULL DEFAULT '',
  analysis_summary TEXT NOT NULL DEFAULT '',
  analyzed_at TEXT,
  provider TEXT NOT NULL DEFAULT '',
  model TEXT NOT NULL DEFAULT '',
  analysis_status TEXT NOT NULL DEFAULT 'none',
  analysis_error TEXT NOT NULL DEFAULT '',
  analysis_message TEXT NOT NULL DEFAULT '',
  profile_json TEXT NOT NULL DEFAULT '',
  profile_version TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS resume_files (
  resume_id BIGINT PRIMARY KEY REFERENCES resumes(id) ON DELETE CASCADE,
  content BYTEA NOT NULL
);

CREATE TABLE IF NOT EXISTS form_field_rules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key TEXT NOT NULL,
  aliases TEXT NOT NULL DEFAULT '',
  mode TEXT NOT NULL DEFAULT 'text',
  value_from TEXT NOT NULL DEFAULT '',
  value TEXT NOT NULL DEFAULT '',
  sort_order INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS applications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id BIGINT NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  channel TEXT NOT NULL,
  recipient TEXT NOT NULL DEFAULT '',
  resume_id BIGINT,
  cover_letter_id BIGINT,
  status TEXT NOT NULL,
  detail TEXT NOT NULL DEFAULT '',
  attempted_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS form_answers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id BIGINT NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  question TEXT NOT NULL,
  answer TEXT NOT NULL,
  provider TEXT NOT NULL DEFAULT '',
  model TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS ai_answer_cache (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  question_norm TEXT NOT NULL UNIQUE,
  question_raw TEXT NOT NULL,
  kind TEXT NOT NULL DEFAULT 'open',
  answer TEXT NOT NULL,
  provider TEXT NOT NULL DEFAULT '',
  model TEXT NOT NULL DEFAULT '',
  hits INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS copilot_asks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_id BIGINT,
  question TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending',
  answer TEXT NOT NULL DEFAULT '',
  hint TEXT NOT NULL DEFAULT '',
  kind TEXT NOT NULL DEFAULT 'text',
  file_path TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL,
  answered_at TEXT NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS copilot_asks_status_idx ON copilot_asks(status);

CREATE TABLE IF NOT EXISTS queue_jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT NOT NULL,
  payload TEXT NOT NULL,
  status TEXT NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0,
  max_attempts INTEGER NOT NULL DEFAULT 40,
  next_run_at TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  last_error TEXT NOT NULL DEFAULT '',
  result TEXT NOT NULL DEFAULT '',
  created_at TEXT NOT NULL,
  updated_at TEXT NOT NULL,
  progress_log TEXT NOT NULL DEFAULT ''
);

CREATE INDEX IF NOT EXISTS queue_jobs_status_idx ON queue_jobs(status, next_run_at);
CREATE INDEX IF NOT EXISTS queue_jobs_kind_idx ON queue_jobs(kind);

CREATE TABLE IF NOT EXISTS event_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TEXT NOT NULL,
  level TEXT NOT NULL,
  source TEXT NOT NULL,
  message TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS event_logs_created_idx ON event_logs(created_at DESC);

CREATE TABLE IF NOT EXISTS qpid_application_attempts (
  attempt_id TEXT PRIMARY KEY,
  job_id BIGINT NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  state TEXT NOT NULL,
  payload TEXT NOT NULL,
  created_at TEXT NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS qpid_one_active_application ON qpid_application_attempts(job_id) WHERE state != 'failed-before-click';

CREATE TABLE IF NOT EXISTS qpid_application_results (
  attempt_id TEXT PRIMARY KEY,
  job_id BIGINT NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
  state TEXT NOT NULL,
  payload TEXT NOT NULL,
  created_at TEXT NOT NULL
);
